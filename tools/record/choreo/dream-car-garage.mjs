/**
 * 夢想車庫 —— 8 秒，兩個動作，都是「換一台車」。
 *
 * 要證明的事：這八台是真的 3D 模型在跑，不是八張去背圖。
 * 證據不在「轉」，在「換」—— 車換了，車庫的光也跟著換：
 * W202 的暗紅 → MX-5 的暖紅 → Macan 的冷藍。三格顏色完全不同，
 * 縮到作品集那個影格那麼小，看不清楚字也知道整個場景重打了一次燈。
 *
 * 為什麼不用拖曳轉車身：model-viewer 上面掛著 pointer-events:none，
 * 拖不動。車身本來就自己慢慢轉，硬去拖只會錄到「游標在那邊亂晃但畫面沒反應」。
 *
 * 為什麼只挑相鄰的兩台：這個站一次只預載下一台。
 * 從 W202 直接跳 Mustang 會出現將近一秒的全黑等模型 ——
 * 在一支會一直循環的 8 秒影片裡，那一秒黑就是「這站是不是壞了」。
 * 相鄰的那台是熱的，換過去是兩台車疊在一起的交叉溶接，一格都不掉。
 *
 * 收尾停在 Macan 的冷藍，跟開頭的暗紅差最遠 —— 循環的接點交給 xfade 去圓，
 * 讀起來像刻意的轉場，不像影片跳掉。
 */

/**
 * 頂層的這一段等待是有意的，不要刪。
 *
 * 這個站的 load 事件早在八台 glb 讀完之前就發了，它自己的「載入車庫 94%」
 * 還蓋在畫面上。record.mjs 是在 import 這支編排「之後」才記錄裁切點的，
 * 所以放在這裡的等待會被一起裁掉，放在 default 裡的等待則會留在影片開頭。
 * 第一版就是這樣錄出兩秒進度條的。等在這裡 = 觀眾第一格看到的是車，不是進度條。
 */
await new Promise((r) => setTimeout(r, 2600));

export default async function (page, k) {
  // 保險絲：萬一今天特別慢，寧可多等一下也不要錄到載入畫面。
  // 正常情況這行是 0 毫秒（上面那 2.6 秒已經等完了）。
  await page
    .waitForFunction(() => document.querySelector('#loader')?.classList.contains('done'), { timeout: 4000 })
    .catch(() => {});

  await k.sleep(500); // 先看清楚現在停的是哪一台（W202 正在自己慢慢轉）

  // ① 從畫面下緣把游標帶到右側車列，點第二台 —— 一次帶出「這裡有一整排」
  await k.tap(page, '#dots button', { move: 820, settle: 2000, nth: 1 });

  // ② 再往下一格。同樣的手勢再做一次，說的是「八台都可以，隨你點」
  //    settle 給 2 秒，等資訊卡也滑進來，畫面才算收完。
  await k.tap(page, '#dots button', { move: 520, settle: 2000, nth: 2 });

  await page.evaluate(() => window.__curHide());
  await k.sleep(850); // 游標退場，留一拍給車
}
