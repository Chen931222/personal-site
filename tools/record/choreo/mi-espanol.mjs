/**
 * Mi Español —— 8 秒，兩個動作。
 *
 * 要證明的事：這不是一頁排版好看的筆記，是一套查得下去的工具。
 *
 * 第一個動作走側欄 —— 九個分區攤在左邊，點下去整個主欄換掉，
 * 一秒之內就講完「這站有多大」。換到「歌詞分析」是因為它最不像模板：
 * 十四首真的歌、真的歌詞、右邊一塊空著的解析欄在等人點。
 *
 * 第二個動作點歌詞裡有底線的字。那塊空欄會填滿：詞性、中文、時態解釋、
 * 底下還接一張變化表。這是整個站的核心手勢，也是唯一沒辦法用截圖說明的事 ——
 * 靜態圖裡它只是一塊留白，動起來才知道那是留給你的。
 *
 * ⚠️ **不從「今天 Hoy」那頁開場。** 那是預設首頁，但錄影每次都是全新的
 *    瀏覽器 profile，localStorage 是空的 —— 畫面上是 0/30 XP、0 連續天數、
 *    0 到期卡片、0 已學會單字。誠實，但等於在作品集首頁上告訴訪客
 *    「這個站沒人用過」，而這是站主唯一打算拿出去賣的產品。
 *
 *    解法不是去偽造使用數據（那才真的不能做），是**換一頁真的有內容的開場**：
 *    ready() 先切到「對話練習」，那頁是真的西語句子與可點的底線字，
 *    一個 0 都沒有。ready() 跑在 record.mjs 算裁切點之前，所以這一步不會被錄進去。
 *
 * 不捲動。兩個動作都落在同一屏裡，視線只要往右移一次，不用重新找位置。
 * 結尾停在解析欄填滿的狀態，游標先退場，留一拍給那塊剛長出來的內容。
 */

/** 開場前先離開空的儀表板。這一段會被裁掉，不佔影片長度。 */
export async function ready(page) {
  await page.evaluate(() => document.querySelectorAll('button.tab')[1]?.click());
  await page.waitForTimeout(1400);
}

export default async function (page, k) {
  await k.sleep(650); // 先讓人讀到真的西語句子，認出這是什麼站

  // ① 側欄換分區 —— 主欄整片換掉，一次帶出「這裡有九個區」
  await k.tap(page, 'button.tab', { move: 800, settle: 1150, nth: 3 });

  // ② 點歌詞裡有底線的字 —— 右邊那塊空的解析欄填滿，這是這個站的招牌手勢
  await k.tap(page, '#lyrics .w', { move: 850, settle: 1350, nth: 3 });

  await page.evaluate(() => window.__curHide());
  await k.sleep(1150); // 游標退場，留一拍給解析欄
}
