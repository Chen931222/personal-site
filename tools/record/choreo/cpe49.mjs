/**
 * CPE 49 題 —— 8 秒，兩個動作。
 *
 * 要證明的事：這不是一頁長長的筆記，是一個查得動的題庫。
 *
 * 這是這批站裡唯一真的要捲的（3.2 屏），所以第一個動作就用捲的 ——
 * 影格裡多數人只看得到前 2～3 秒，整頁往上跑是那個尺寸下最讀得出來的動作，
 * 游標在小畫面上根本看不見。捲到 y=700 剛好把 9 張題型卡整齊裝滿一屏，
 * 不多不少，這是這個站最好看的一屏。
 *
 * 第二個動作點題型卡（不是點導覽列）—— 點的正是剛剛捲出來的那張，
 * 因果看得懂：選題型 → 換到題庫、篩選自動套上、導覽列的 active 也跟著跳。
 * 一個站會不會動，看的是點下去之後狀態有沒有真的變。
 *
 * 沒有第三個動作。開「看解法」的彈窗很漂亮，但那要先捲到題卡才點得到，
 * 三個動作塞進 8 秒，等於三個都看不清楚。
 */
export default async function (page, k) {
  await k.sleep(750); // 先讓標題站住 —— 第一格就要看得出這站在幹嘛

  // ① 捲出 9 大題型。收尾停一下，讓人來得及讀完卡片上的字。
  await k.scrollTo(page, 700, 1450);
  await k.sleep(420);

  // ② 挑「二維陣列 / 模擬」（最大的題型，0/8）。從畫面下緣斜著上去，一次到位。
  //    游標移動不能拖 —— 影格縮到那個尺寸，游標幾乎看不見，
  //    移太久畫面等於停格，看起來像影片卡住。
  await k.tap(page, 'a.chapter-card', { move: 620, settle: 1500, nth: 6 });

  await page.evaluate(() => window.__curHide());
  await k.sleep(1150); // 游標退場，留一拍給新出現的題庫
}
